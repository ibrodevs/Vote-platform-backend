"""Единственное место, где решается, что можно прочитать с реплики (ТЗ п.46).

ПОЧЕМУ НЕ АВТОМАТИЧЕСКИЙ РОУТИНГ
---------------------------------
Роутер Django выбирает базу по модели. Нужный здесь критерий — не модель,
а смысл запроса. `VoteRecord` читается и в проверке «голосовал ли я»
(критично, отставание недопустимо), и в отчёте по явке (некритично).
Роутер по модели различить их не может.

Поэтому чтения НЕ роутятся автоматически. По умолчанию всё идёт на primary,
и только запросы, для которых устаревание заведомо безопасно, помечаются
вручную вызовом `eventual()`.

Направление ошибки выбрано намеренно:

    забыли пометить  → лишняя нагрузка на primary, данные верные
    забыли запретить → студент видит «вы ещё не голосовали» после голоса
                       и нажимает кнопку второй раз

Вторая ошибка недопустима (ТЗ п.46), первая — всего лишь неоптимальна.

ЧТО НЕЛЬЗЯ ПОМЕЧАТЬ КАК eventual
---------------------------------
- `POST /vote` и всё, что он читает;
- статус голосования студента;
- admin start/finish выборов и любые проверки перед сменой состояния;
- результаты выборов после завершения;
- всё, что участвует в решении «можно ли голосовать».
"""
from typing import TypeVar

from django.conf import settings
from django.db.models import QuerySet

# Алиас реплики в DATABASES. Существует только когда задан DB_REPLICA_HOST:
# без него `eventual()` возвращает запрос на primary, и поведение системы
# ничем не отличается от развёртывания без реплики.
REPLICA_ALIAS = "replica"
PRIMARY_ALIAS = "default"

_QS = TypeVar("_QS", bound=QuerySet)


def replica_configured() -> bool:
    """Настроена ли отдельная реплика чтения."""
    return REPLICA_ALIAS in settings.DATABASES


def read_alias() -> str:
    """Алиас для чтений, допускающих отставание."""
    return REPLICA_ALIAS if replica_configured() else PRIMARY_ALIAS


def eventual(queryset: _QS) -> _QS:
    """Помечает чтение как допускающее отставание реплики.

    Применяется ТОЛЬКО к данным, устаревание которых на секунды безвредно
    и никак не связано с голосованием: новости, FAQ, статические страницы,
    справочник вузов.

    Без настроенной реплики возвращает тот же запрос к primary — так что
    пометка безопасна и в однобазовом развёртывании.
    """
    return queryset.using(read_alias())
