"""Ограниченный поиск (ТЗ п.94).

Поиск по одному-двум символам совпадает почти со всей таблицей: PostgreSQL
читает её целиком, сортирует результат и отдаёт первые 20 строк. Полезность
такого запроса нулевая, стоимость — полный скан.

ПОЧЕМУ НЕ TRIGRAM-ИНДЕКС
------------------------
Вариант с `pg_trgm` + GIN по выражению `UPPER(field::text)` был построен
и измерен на 200 000 студентов. Результат:

  селективный запрос, поиск внутри вуза  : 10 мс и без индекса
  селективный запрос по всей таблице     : 44 -> 17 мс с индексом
  НЕселективный запрос                   : 48 -> 73 мс, то есть ХУЖЕ
  bulk_create 20 000 строк               : 1.21 -> 2.27 с (+88%)
  размер индексов                        : +22 МБ на таблицу в 48 МБ

Импорт студентов — явное требование ТЗ п.41, и почти двукратное замедление
записи ради ускорения админского поиска, который и так укладывается в 10 мс
в реальном сценарии, невыгодно. Решение пересматривается по данным
нагрузочного тестирования (этап 10), измерения — в docs/PERFORMANCE.md.
"""
from rest_framework.filters import SearchFilter

MIN_SEARCH_LENGTH = 3


class MinLengthSearchFilter(SearchFilter):
    """SearchFilter, игнорирующий слишком короткие запросы.

    Короткий запрос именно игнорируется, а не отвергается ошибкой: пользователь
    набирает строку по символу, и ошибка на каждом первом символе была бы
    хуже, чем просто немного подождать.
    """

    min_search_length = MIN_SEARCH_LENGTH

    def get_search_terms(self, request):
        terms = super().get_search_terms(request)
        return [t for t in terms if len(t) >= self.min_search_length]
