"""Политика кэширования (ТЗ п.21, 22, 24, 28, 29, 113).

ТЗ п.113 требует для каждого неймспейса знать TTL, примерный размер элемента,
оценку числа ключей и политику вытеснения. Держать это в головах нельзя —
поэтому всё здесь, рядом с обоснованием каждого решения.

┌──────────────────────┬─────────┬──────────┬─────────────────────────┐
│ Неймспейс            │ TTL     │ ~размер  │ Оценка числа ключей     │
├──────────────────────┼─────────┼──────────┼─────────────────────────┤
│ student:*:principal  │ 15 мин  │ ~200 Б   │ активные студенты       │
│ student:*:vote:*     │ 7 суток │ ~30 Б    │ голоса за период        │
│ election:*:turnout   │ 10 с    │ ~100 Б   │ идущие выборы           │
│ election:*:results   │ 24 часа │ ~2–20 КБ │ завершённые выборы      │
│ election:*:public    │ 5 мин   │ ~2–20 КБ │ выборы                  │
└──────────────────────┴─────────┴──────────┴─────────────────────────┘

Порядок величин: при 200 000 студентов и 100 000 голосов это примерно
40 МБ principal + 3 МБ статусов + единицы МБ на выборы. Для Redis
с `maxmemory-policy allkeys-lru` этого достаточно с большим запасом;
рекомендация по `maxmemory` — в docs/PERFORMANCE.md.

ЧТО НЕ КЭШИРУЕТСЯ И ПОЧЕМУ
--------------------------
`has_voted = false`. Значение меняется в любой момент, и устаревшее «нет»
после успешного голоса показало бы студенту кнопку голосования повторно —
худший из возможных багов в этой системе. Цена отказа — один индексный
запрос стоимостью 0.06 мс (измерено, docs/PERFORMANCE.md).

Результаты НЕзавершённых выборов. Кэш пережил бы смену состояния и мог бы
отдать цифры, которые уже нельзя показывать (ТЗ п.51).

Решение о приёме голоса. `POST /vote` проверяет статус выборов и факт участия
в транзакции PostgreSQL и кэшу не доверяет никогда (ТЗ п.22).
"""


class CachePolicy:
    """TTL в секундах. Каждое значение — с обоснованием, а не «на глаз»."""

    # Личность студента. Отзыв работает через явную инвалидацию и сверку
    # auth_version, а не через истечение TTL — TTL лишь вторая линия (ТЗ п.24).
    STUDENT_PRINCIPAL = 15 * 60

    # Положительный факт участия. Необратим: проголосовавший не может
    # «разголосоваться». Живёт дольше любых разумных выборов.
    VOTE_STATUS_POSITIVE = 7 * 24 * 60 * 60

    # Явка идущих выборов. ТЗ п.29 прямо допускает задержку в несколько секунд;
    # взамен снимается COUNT по таблице голосов с каждого запроса.
    ELECTION_TURNOUT = 10

    # Итоги ЗАВЕРШЁННЫХ выборов. После завершения они неизменны (ТЗ п.28),
    # поэтому кэшируются надолго. Незавершённые не кэшируются вовсе.
    ELECTION_FINAL_RESULTS = 24 * 60 * 60

    # Публичные данные выборов: название, описание, даты, список кандидатов.
    # Инвалидируются явно при любом изменении выборов или кандидатов.
    ELECTION_PUBLIC = 5 * 60


# Заголовки Cache-Control (ТЗ п.96, 60)
PRIVATE_NO_STORE = "private, no-store"
PUBLIC_SHORT = "public, max-age=60"
