"""Политика кэширования (ТЗ п.21, 22, 24, 28, 29, 113).

Кэш — ускоритель, PostgreSQL остаётся источником истины. Персональное
`has_voted = false` принципиально не кэшируется: после успешного голоса такое
значение могло бы показать кнопку голосования повторно.
"""


class CachePolicy:
    """TTL в секундах. Каждое значение имеет отдельный смысл."""

    # Личность студента. Отзыв работает через auth_version + инвалидацию.
    STUDENT_PRINCIPAL = 15 * 60

    # Положительный факт участия необратим и безопасно кэшируется надолго.
    VOTE_STATUS_POSITIVE = 7 * 24 * 60 * 60

    # Общая, НЕперсональная часть активных выборов университета. Две секунды
    # снимают ORM + сериализацию кандидатов с каждого authenticated request,
    # но состояние открытия/закрытия не может застрять надолго. Изменения
    # Election/Candidate дополнительно инвалидируют этот ключ явно.
    ACTIVE_ELECTIONS_CATALOG = 2

    # Явка может отставать на несколько секунд.
    ELECTION_TURNOUT = 10

    # Итоги завершённых выборов после завершения неизменны.
    ELECTION_FINAL_RESULTS = 24 * 60 * 60

    # Публичные данные выборов инвалидируются при изменениях.
    ELECTION_PUBLIC = 5 * 60


PRIVATE_NO_STORE = "private, no-store"
PUBLIC_SHORT = "public, max-age=60"
